// 3–4 слога, 5–20 слогов, 21 слог, 22 слога ...
function syllableWord(n) {
  const lastTwo = n % 100;
  const last = n % 10;
  if (lastTwo >= 11 && lastTwo <= 14) return 'слогов';
  if (last === 1) return 'слог';
  if (last >= 2 && last <= 4) return 'слога';
  return 'слогов';
}

