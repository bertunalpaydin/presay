    'Whisper speech models (not served by this site)',
    'The browser downloads Whisper model files (OpenAI, MIT licence) from Hugging Face, and the ONNX Runtime WebAssembly files (Microsoft, MIT licence) from the jsDelivr or unpkg CDN.',
