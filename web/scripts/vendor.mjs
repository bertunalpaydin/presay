#!/usr/bin/env node
// Copies third-party files into site/:
//   - Gentium Book Plus and Schibsted Grotesk web fonts (SIL Open Font License)
//   - vendor/versions.js, the pinned versions of the files loaded from the CDN
//   - a local copy of the Transformers.js browser bundle
//
// Run with:  npm run vendor
// The fonts, versions.js and licences.txt are committed, so the site needs no
// build step to deploy. The Transformers.js copy is not: the browser loads the
// same file from jsDelivr, and the local copy is only a fallback for working
// offline.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SITE = path.join(ROOT, 'site');
const nodeModules = path.join(ROOT, 'node_modules');
const readPackage = (name) => JSON.parse(fs.readFileSync(path.join(nodeModules, name, 'package.json'), 'utf8'));

function copy(from, to) {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
  console.log(`${path.relative(ROOT, to)} (${(fs.statSync(to).size / 1024).toFixed(0)} KB)`);
}

// Transformers.js: the self-contained browser build (no bundler needed).
const transformersPkg = readPackage('@huggingface/transformers');
const ortPkg = readPackage('onnxruntime-web');
copy(
  path.join(nodeModules, '@huggingface/transformers/dist/transformers.min.js'),
  path.join(SITE, 'vendor/transformers.min.js'),
);
fs.writeFileSync(
  path.join(SITE, 'vendor/versions.js'),
  `// Generated by scripts/vendor.mjs\nexport const TRANSFORMERS_VERSION = '${transformersPkg.version}';\nexport const ORT_VERSION = '${ortPkg.version}';\n`,
);
console.log(`site/vendor/versions.js (transformers ${transformersPkg.version}, onnxruntime-web ${ortPkg.version})`);

// Fonts.
const FONTS = [
  ['gentium-book-plus', ['latin', 'latin-ext', 'greek'], ['400-normal', '700-normal', '400-italic']],
  ['schibsted-grotesk', ['latin', 'latin-ext'], ['400-normal', '500-normal', '600-normal']],
];
for (const [family, subsets, styles] of FONTS) {
  for (const subset of subsets) {
    for (const style of styles) {
      const file = `${family}-${subset}-${style}.woff2`;
      copy(path.join(nodeModules, `@fontsource/${family}/files/${file}`), path.join(SITE, 'assets/fonts', file));
    }
  }
  copy(path.join(nodeModules, `@fontsource/${family}/LICENSE`), path.join(SITE, 'assets/fonts', `${family}-LICENSE.txt`));
}

